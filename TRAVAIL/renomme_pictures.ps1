# Renommage des images vers le code COMPLET, avec son prefixe de livre.
# Genere le 31/08/2026. A lancer DEPUIS LE DOSSIER DU PROJET (pas depuis TRAVAIL).
#
# ATTENTION AU DOSSIER 'SPELL' : malgre son nom, il ne contient pas des images de
# SORTS mais des images de TALENTS - T0089, T0088_FEU, T0080_SIGMAR. C'est coherent
# avec CheminSortImage, dont le parametre s'appelle CodeTalent. Les codes de cette
# section sont donc des talents, plus les TRONCS des familles generiques : l'image
# T0088.png sert a tout 'T0088_*', et CheminSortImage la trouve en coupant au '_'.
#
# Les identifiants COMBINES (A/B) sont ecartes : ce sont des declarations de choix,
# jamais des noms de fichiers.
#
# Deux garde-fous :
#  - un fichier deja prefixe est ignore, donc le script est REJOUABLE ;
#  - le suffixe chiffre n'est accepte QUE dans SPECIE, ou il porte l'indice de
#    l'illustration (RACE_HELF1). Sans cela le code WORK10 capturerait WORK100.png.
#
$Simulation = $false   # <-- passer a $false pour renommer pour de vrai
$Base = "DATABASE\PICTURES"
$n = 0

if (-not (Test-Path $Base)) {
  Write-Host "ERREUR : $Base introuvable. Lancer ce script DEPUIS le dossier du projet." -ForegroundColor Red
  exit 1
}

function Renomme($Dossier, $Court, $Complet, $Chiffres) {
  $chemin = Join-Path $Base $Dossier
  if (-not (Test-Path $chemin)) { return }
  $motif = if ($Chiffres) { "^([0-9]*)(_TRANS)?\.(png|PNG)$" } else { "^(_TRANS)?\.(png|PNG)$" }
  Get-ChildItem -Path $chemin -Filter "$Court*" -File | ForEach-Object {
    if ($_.Name -match "^[A-Z0-9]+-") { return }
    $reste = $_.Name.Substring($Court.Length)
    if ($reste -notmatch $motif) { return }
    $script:n++
    Rename-Item -LiteralPath $_.FullName -NewName ($Complet + $reste) -WhatIf:$script:Simulation
  }
}

